test('the open daily game keeps yesterday’s assignment until the player chooses the next day', async (t) => {
  const { page, open, place, action } = await setup(t);
  await open('daily');
  const original = await page.locator('.cut-date').innerText();
  assert.match(original, /2026-11-20/);
  await place('exterior', 0);
  await page.clock.fastForward(30000);
  await page.reload();
  await expect(page.locator('.cut-date')).toHaveText(original);
  await action('new-day').click();
  await expect(page.locator('.cut-date')).toHaveText('2026-11-21 UTC');
  await expect(page.locator('[data-slot="0"]')).toContainText('Place shot');
});
