const assert = require('node:assert/strict');
const { test } = require('node:test');
const fs = require('node:fs');
const http = require('node:http');
const path = require('node:path');
const { chromium, expect } = require('playwright/test');
const files = path.resolve(__dirname, '..');
const types = { '.js': 'text/javascript', '.webp': 'image/webp', '.html': 'text/html', '.css': 'text/css', '.woff2': 'font/woff2', '.svg': 'image/svg+xml' };
async function setup(t) {
  const server = http.createServer((req, res) => {
    const url = new URL(req.url, 'http://localhost');
    const file = path.join(files, url.pathname.replace(/^\/abdulrhman\//, '') + (url.pathname.endsWith('/') ? 'index.html' : ''));
    if (!url.pathname.startsWith('/abdulrhman/') || !file.startsWith(files + path.sep) || !fs.existsSync(file) || !fs.statSync(file).isFile()) {
      res.writeHead(404);
      res.end();
      return;
    }
    res.setHeader('Content-Type', types[path.extname(file)] || 'application/octet-stream');
    fs.createReadStream(file).pipe(res);
  });
  await new Promise(resolve => server.listen(0, '127.0.0.1', resolve));
  t.after(() => server.close());
  const origin = 'http://127.0.0.1:' + server.address().port;
  const browser = await chromium.launch({ executablePath: process.env.CHROMIUM_PATH || '/usr/bin/chromium', args: ['--no-sandbox'] });
  t.after(() => browser.close());
  const page = await browser.newPage({ viewport: { width: 320, height: 812 }, reducedMotion: 'reduce' });
  const errors = [];
  page.on('pageerror', e => errors.push(e.message));
  t.after(() => assert.deepEqual(errors, []));
  await page.route('**/*', r => r.request().url().startsWith(origin + '/') ? r.continue() : r.abort());
  await page.clock.install({ time: new Date('2026-11-20T23:59:39Z') });
  const open = async (id, lang = 'en') => {
    await page.goto(origin + '/abdulrhman/raven/after-show/content.html?activity=' + id + '&lang=' + lang);
    await expect(page.locator('.after-cut')).toBeVisible();
  };
  const action = id => page.locator('[data-edit-action="' + id + '"]');
  const place = async (id, i) => {
    await page.locator('[data-shot="' + id + '"]').click();
    await page.locator('[data-slot="' + i + '"]').click();
  };
  return { page, open, place, action };
}
test('plays the actual 12-second cut, pauses, shows a timed fallback and preserves the chosen sequence', async (t) => {
  const { page, open, place, action } = await setup(t);
  const blocked = '**/after-show/assets/hand.webp';
  await page.route(blocked, r => r.abort());
  await open('edit', 'ar');
  await place('exterior', 0);
  await place('hand', 1);
  await place('envelope', 2);
  await action('play').click();
  await expect(page.locator('[data-current-shot=exterior]')).toBeVisible();
  await page.clock.fastForward(5100);
  await expect(page.locator('[data-current-shot=hand] .cut-fallback')).toBeVisible();
  await action('pause').click();
  const paused = await page.locator('[data-edit-clock]').innerText();
  await page.clock.fastForward(4800);
  assert.equal(await page.locator('[data-edit-clock]').innerText(), paused);
  await page.unroute(blocked);
  await action('retry-image').click();
  await expect.poll(() => page.locator('[data-current-shot=hand]>img').evaluate(n => n.naturalWidth)).toBeGreaterThan(0);
  await action('pause').click();
  await page.clock.fastForward(7200);
  await expect(page.locator('[data-edit-result]')).toHaveAttribute('data-time', 'true');
  await expect(page.locator('[data-edit-result]')).toHaveAttribute('data-order', 'true');
  await place('envelope', 0);
  await expect(page.locator('[data-slot="2"]')).toContainText('واجهة المبنى');
  await action('play').click();
  await page.clock.fastForward(12500);
  await expect(page.locator('[data-edit-result]')).toHaveAttribute('data-order', 'false');
  await action('studio').click();
  assert.match(await page.locator('[data-edit-studio-confirm]').getAttribute('href'), /afterShow=envelope%2Chand%2Cexterior/);
  await action('suggest').click();
  await action('apply-suggestion').click();
  await action('version-A').click();
  await expect(page.locator('[data-slot="0"]')).toContainText('الظرف');
  assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth));
});
